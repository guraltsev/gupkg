"""Generate the 1.0 package launchers, ``install.cmd`` and ``gupkg-tui.cmd``.

``launcher_text(verb)`` returns the text of one launcher and ``write_launchers(...)``
writes them into a package directory. Both launchers come from one template.

A launcher lives at ``<root>\\<name>\\<version>\\`` and starts the gupkg that manages
that root: the root forwarder ``%~dp0..\\..\\.gupkg\\gupkg.cmd`` first (unless
``--no-system-gupkg=true`` is given), then the gupkg bundled in the same folder, and
exit code 9009 with the way to get gupkg when neither exists. Exit code 6, which an
installed gupkg returns for a package it cannot handle, re-runs the command with the
bundled gupkg. ``PATH``, the registry, AppData, ProgramData and the current directory
are never searched (design section 21.3, decisions D16 and D32).

The elevated-run verification of design section 21.3 (decision D30) is not carried by
this template. A launcher therefore refuses to run elevated, and fails closed: it
refuses when it cannot tell, rather than trusting folders a standard user can change.
"""

from __future__ import annotations

from pathlib import Path

LAUNCHERS = {"install.cmd": "install", "gupkg-tui.cmd": "tui"}

_TEMPLATE = r"""@echo off
setlocal EnableExtensions DisableDelayedExpansion
rem __TITLE__
rem Generated by gupkg-migrate. Which gupkg runs: the root forwarder of the root that holds this
rem package, then the gupkg bundled in this folder. PATH, the registry, AppData, ProgramData and
rem the current directory are never searched.

rem An elevated run must first verify that everything it would run is admin-only. This launcher
rem cannot do that, so it refuses; it also refuses when it cannot tell whether it is elevated.
if not exist "%SystemRoot%\System32\fltmc.exe" goto :refuse_elevated
"%SystemRoot%\System32\fltmc.exe" >nul 2>&1
if not errorlevel 1 goto :refuse_elevated

set "GUPKG_HERE=%~dp0"
set "GUPKG_FORWARDER=%GUPKG_HERE%..\..\.gupkg\gupkg.cmd"
set "GUPKG_BUNDLED=%GUPKG_HERE%gupkg\gupkg.cmd"
set "GUPKG_SKIP_FORWARDER="
set "GUPKG_EXTRA="

:collect
if "%~1"=="" goto :collected
rem cmd.exe splits an unquoted --no-system-gupkg=true at the "=", so the option arrives as
rem two arguments (or as one when quoted); both spellings are consumed here.
if /I "%~1"=="--no-system-gupkg=true" goto :skip_forwarder
if /I "%~1"=="--no-system-gupkg" goto :system_option
set "GUPKG_EXTRA=%GUPKG_EXTRA% "%~1""
shift
goto :collect
:skip_forwarder
set "GUPKG_SKIP_FORWARDER=1"
shift
goto :collect
:system_option
shift
set "GUPKG_SKIP_FORWARDER=1"
if /I "%~1"=="true" shift
if /I "%~1"=="false" (set "GUPKG_SKIP_FORWARDER=" & shift)
goto :collect
:collected

set "GUPKG_RUN="
if not defined GUPKG_SKIP_FORWARDER if exist "%GUPKG_FORWARDER%" if not exist "%GUPKG_FORWARDER%\NUL" set "GUPKG_RUN=%GUPKG_FORWARDER%"
if not defined GUPKG_RUN if exist "%GUPKG_BUNDLED%" if not exist "%GUPKG_BUNDLED%\NUL" set "GUPKG_RUN=%GUPKG_BUNDLED%"
if not defined GUPKG_RUN goto :no_gupkg

call "%GUPKG_RUN%" __VERB__ "%GUPKG_HERE%."%GUPKG_EXTRA%
set "GUPKG_EXIT=%ERRORLEVEL%"

rem Exit code 6: the installed gupkg cannot handle this package. Use the bundled one, if any.
if not "%GUPKG_EXIT%"=="6" goto :finish
if not "%GUPKG_RUN%"=="%GUPKG_FORWARDER%" goto :finish
if not exist "%GUPKG_BUNDLED%" goto :finish
>&2 echo [gupkg] The installed gupkg cannot handle this package; using the gupkg bundled with it.
call "%GUPKG_BUNDLED%" __VERB__ "%GUPKG_HERE%."%GUPKG_EXTRA%
set "GUPKG_EXIT=%ERRORLEVEL%"

:finish
if not "%GUPKG_EXIT%"=="0" if not defined GUPKG_NO_PAUSE pause
exit /b %GUPKG_EXIT%

:no_gupkg
>&2 echo [gupkg] gupkg is not installed, and none is bundled with this package.
>&2 echo [gupkg] Install gupkg first: https://github.com/guraltsev/gupkg ^(download gupkg-bootstrap.cmd and run it^).
if not defined GUPKG_NO_PAUSE pause
exit /b 9009

:refuse_elevated
>&2 echo [gupkg] This launcher does not run elevated. Run gupkg from an installed system gupkg instead.
if not defined GUPKG_NO_PAUSE pause
exit /b 1
"""

_TITLES = {
    "install": "Installs this package with gupkg.",
    "tui": "Opens the gupkg text interface (check-updates, update, repair, uninstall, logs) for this package.",
}


def launcher_text(verb: str) -> str:
    """Return the text of one launcher.

    Parameters
    ----------
    verb : str
        ``"install"`` for ``install.cmd`` or ``"tui"`` for ``gupkg-tui.cmd``.

    Returns
    -------
    str
        The launcher with Windows line endings.

    Raises
    ------
    ValueError
        If *verb* is not a launcher command.
    """
    if verb not in _TITLES:
        raise ValueError(f"unknown launcher command: {verb}")
    text = _TEMPLATE.replace("__TITLE__", _TITLES[verb]).replace("__VERB__", verb)
    return text.replace("\r\n", "\n").replace("\n", "\r\n")


def write_launchers(directory: Path, names: tuple[str, ...] = tuple(LAUNCHERS)) -> list[Path]:
    """Write launchers into *directory*, replacing existing ones.

    Parameters
    ----------
    directory : Path
        The version directory.
    names : tuple of str, optional
        File names to write; both launchers by default.

    Returns
    -------
    list of Path
        The files written.
    """
    written = []
    for name in names:
        path = Path(directory) / name
        path.write_bytes(launcher_text(LAUNCHERS[name]).encode("ascii"))
        written.append(path)
    return written
