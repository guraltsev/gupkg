"""Check a bundled gupkg tree against the manifest its release was built with.

A release carries ``gupkg/MANIFEST.sha256`` in its version directory: one ``<sha256>  <relative path>``
line for every file of the bundled tree ``gupkg/``, with paths relative to the version directory
(``gupkg/gupkg/cli.py``), sorted by path. The build computes it; this module only *checks* it. Hashes are
never generated by installed code, and nothing is repaired here: a damaged install is fixed by installing
the release again.

Usage and API
-------------
``verify_version_directory(version_root)`` compares the bundled tree ``<version_root>/gupkg`` with its
manifest; ``verify_tree(tree, manifest)`` compares any folder with the entries of a manifest (the ``App``
that was copied from a bundled tree, or a tree that was just extracted). The returned ``IntegrityReport``
lists modified, missing, and extra files. ``read_manifest(path)`` parses a manifest for tools that need
the expected digests.

Implementation Approach
-----------------------
Every file below the tree is hashed and compared with the manifest's ``gupkg/`` entries. The rest of a
version directory (``pkg.toml``, ``pkg.local``, the launchers) belongs to the package and is not covered:
``check-updates`` writes those files itself, so they need not be byte-identical to the ZIP's. ``__pycache__``
is not exempt: the release ships no bytecode and installed Python runs with ``-B``, so any ``.pyc`` is
reported as extra (a planted one would otherwise run in the elevated trust path).
"""

from __future__ import annotations

import hashlib
import os
import re
from dataclasses import dataclass
from pathlib import Path

# Manifest location, relative to the version directory that it describes.
MANIFEST_RELATIVE_PATH = "gupkg/MANIFEST.sha256"

# The folder of a version directory that holds the bundled tree; manifest entries start with it.
TREE_FOLDER = "gupkg"

_LINE = re.compile(r"^(?P<digest>[0-9a-f]{64})  (?P<path>\S(?:.*\S)?)$")


class ManifestError(ValueError):
    """Report a manifest that is missing, malformed, or names an unsafe path."""


@dataclass(frozen=True)
class IntegrityReport:
    """List how a version directory differs from its manifest.

    ``manifest_found`` is ``False`` when the manifest itself is absent; the
    other lists are then empty because there is nothing to compare with.
    """

    manifest_found: bool
    modified: tuple[str, ...] = ()
    missing: tuple[str, ...] = ()
    extra: tuple[str, ...] = ()

    @property
    def ok(self) -> bool:
        """Return whether the directory matches its manifest exactly."""
        return self.manifest_found and not (self.modified or self.missing or self.extra)

    def problems(self) -> list[str]:
        """Return one human line per difference, in a stable order."""
        if not self.manifest_found:
            return [f"{MANIFEST_RELATIVE_PATH} is missing"]
        return (
            [f"modified: {path}" for path in self.modified]
            + [f"missing: {path}" for path in self.missing]
            + [f"extra: {path}" for path in self.extra]
        )


def verify_version_directory(version_root: Path) -> IntegrityReport:
    """Compare the bundled tree ``<version_root>/gupkg`` with ``gupkg/MANIFEST.sha256``.

    Parameters
    ----------
    version_root : Path
        Installed or staged version directory (the one holding ``pkg.toml`` and the ``gupkg`` folder).

    Returns
    -------
    IntegrityReport
        Modified, missing, and extra files; empty lists mean an exact match.

    Raises
    ------
    ManifestError
        If the manifest exists but cannot be parsed.
    """
    root = Path(version_root)
    return verify_tree(root / TREE_FOLDER, root / MANIFEST_RELATIVE_PATH)


def verify_tree(tree: Path, manifest_path: Path) -> IntegrityReport:
    """Compare the folder *tree* with the ``gupkg/`` entries of the manifest at *manifest_path*.

    Parameters
    ----------
    tree : Path
        The folder to check: a bundled tree, or the ``App`` that was copied from one (the same files, the same layout).
    manifest_path : Path
        A ``MANIFEST.sha256`` whose entries start with ``gupkg/``; the files of *tree* are compared under that name, so a report names ``gupkg/gupkg/cli.py`` whichever copy was checked.

    Returns
    -------
    IntegrityReport
        Modified, missing, and extra files; empty lists mean an exact match.

    Raises
    ------
    ManifestError
        If the manifest exists but cannot be parsed.
    """
    manifest_path, tree = Path(manifest_path), Path(tree)
    if not manifest_path.is_file():
        return IntegrityReport(manifest_found=False)
    prefix = TREE_FOLDER + "/"
    expected = {path: digest for path, digest in read_manifest(manifest_path).items() if path.startswith(prefix)}

    # Hash every file of the tree and compare it with the manifest's digest; the manifest never lists itself.
    actual: dict[str, Path] = {}
    for current, _folders, files in os.walk(tree):
        relative_folder = Path(current).relative_to(tree)
        for name in files:
            relative = (relative_folder / name).as_posix()
            if relative == "MANIFEST.sha256" and not relative_folder.parts:
                continue
            actual[prefix + relative] = Path(current) / name

    modified = sorted(
        path for path, digest in expected.items() if path in actual and _sha256(actual[path]) != digest
    )
    missing = sorted(path for path in expected if path not in actual)
    extra = sorted(path for path in actual if path not in expected)
    return IntegrityReport(True, tuple(modified), tuple(missing), tuple(extra))


def read_manifest(path: Path) -> dict[str, str]:
    """Parse a manifest into ``{relative path: sha256}``.

    Raises
    ------
    ManifestError
        If the file cannot be read, a line is malformed, or a path is absolute
        or leaves the version directory.
    """
    try:
        text = Path(path).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise ManifestError(f"Cannot read {path}: {error}") from error

    # One entry per line; a path that could point outside the tree is refused
    # because the manifest decides which files get hashed and trusted.
    entries: dict[str, str] = {}
    for number, line in enumerate(text.splitlines(), start=1):
        match = _LINE.match(line)
        if match is None:
            raise ManifestError(f"{path}, line {number}: expected '<sha256>  <relative path>'")
        relative = match["path"]
        if relative in entries:
            raise ManifestError(f"{path}, line {number}: duplicate path {relative!r}")
        parts = relative.split("/")
        if relative.startswith("/") or ":" in relative or "\\" in relative or ".." in parts or "" in parts:
            raise ManifestError(f"{path}, line {number}: unsafe path {relative!r}")
        entries[relative] = match["digest"]
    return entries


def _sha256(path: Path) -> str:
    """Return the lower-case SHA-256 digest of one file."""
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()
