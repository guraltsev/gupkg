# Default registry: the official package repository. A repository URL is fetched
# with Git when a trusted Git exists and as its ZIP archive otherwise; any other
# source must be the URL of a ZIP archive.
OFFICIAL_SOURCE = "https://github.com/guraltsev/gupkg-registry.git"

# Name of the folder, inside the cache, that holds the official registry. Other
# registries would get folders of their own.
REGISTRY_NAME = "gupkg-registry"


@dataclass(frozen=True)
class RegistryPackage:
    """Describe one validated catalog selector and its install seed."""

    selector: str
    root: Path
    version_path: Path


@dataclass(frozen=True)
class RegistryState:
    """Report the active cached revision and the most recent sync outcome."""

    cache_root: Path
    revision: str | None = None
    source: str | None = None
    synchronized_at: str | None = None
    last_failure: str | None = None

    @property
    def tree_path(self) -> Path | None:
        """Return the active ``pkgs`` tree when one is available."""
        if self.revision is None:
            return None
        candidate = self.cache_root / REGISTRY_NAME / "trees" / self.revision / "pkgs"
        return candidate if candidate.is_dir() else None


def require_trusted_cache(cache_root: Path, system: System) -> None:
    """Refuse a registry cache that an elevated run cannot trust.

    The cache supplies package templates, download addresses and hashes that an
    elevated install would act on, so under elevation its folder (or, before it
    exists, the nearest existing parent) must be writable by administrators only.

    Raises
    ------
    ConfigValidationError
        If the run is elevated and the location is not admin-only.
    """
    if not is_elevated_run(system):
        return

    # A cache that does not exist yet will be created inside its nearest parent.
    probe = Path(cache_root).absolute()
    while not probe.exists() and probe.parent != probe:
        probe = probe.parent
    try:
        require_admin_only(system, probe)
    except UntrustedLocationError as exc:
        raise ConfigValidationError(
            f"Refusing the registry cache {cache_root} for an elevated run: {exc} "
            "Set [registry] cache in gupkg-config.toml to a folder only administrators can modify."
        ) from exc


def registry_status(cache_root: Path, system: System) -> RegistryState:
    """Read cache state without contacting Git or creating directories."""
    require_trusted_cache(cache_root, system)
    state_path = Path(cache_root) / REGISTRY_NAME / "state.toml"
    if not state_path.is_file():
        return RegistryState(Path(cache_root))
    # The state is regenerated by the next sync, so an unreadable file means "never synchronized".
    try:
        values = read_toml(state_path)
    except (OSError, tomllib.TOMLDecodeError):
        return RegistryState(Path(cache_root))
    return RegistryState(
        Path(cache_root),
        revision=values.get("revision") or None,
        source=values.get("source") or None,
        synchronized_at=values.get("synchronized_at") or None,
        last_failure=values.get("last_failure") or None,
    )


def validate_registry_tree(pkgs_root: Path) -> list[RegistryPackage]:
    """Validate a registry checkout and return deterministic seeds.

    Parameters
    ----------
    pkgs_root : Path
        Registry root: one flat child directory per package selector. Top-level
        files and entries starting with "." or "_" are ignored.

    Returns
    -------
    list[RegistryPackage]
        Validated package seeds sorted case-insensitively by selector.

    Raises
    ------
    ConfigValidationError
        If the tree contains unsafe filesystem entries, selector collisions,
        malformed manifests, or unhealthy hook references.
    """
    pkgs_root = Path(pkgs_root)
    if not pkgs_root.is_dir() or pkgs_root.is_symlink():
        raise ConfigValidationError(f"Registry tree is not a directory: {pkgs_root}")
    packages: list[RegistryPackage] = []
    seen: dict[str, str] = {}
    for selector_path in sorted(pkgs_root.iterdir(), key=lambda item: (item.name.casefold(), item.name)):
        _reject_reparse(selector_path, "registry selector")
        # Top-level files (README, LICENSE) and entries starting with "." or "_"
        # (.git, .github, _tests, _tools) are repository furniture, not packages.
        if selector_path.name.startswith((".", "_")) or not selector_path.is_dir():
            continue
        selector = selector_path.name
        key = selector.casefold()
        if key in seen:
            raise ConfigValidationError(
                f"Duplicate registry selector: {seen[key]} and {selector}"
            )
        seen[key] = selector
        versions = [
            item for item in selector_path.iterdir()
            if is_package_directory(item)
        ]
        if len(versions) != 1:
            raise ConfigValidationError(
                f"Registry selector '{selector}' must contain exactly one version seed"
            )
        version_path = versions[0]
        _validate_tree_entries(version_path, version_path)
        manifest = version_path / "pkg.toml"
        if not manifest.is_file():
            raise ConfigValidationError(f"Registry seed has no pkg.toml: {version_path}")
        identity = PackageIdentity.from_version_path(
            selector_path, version_path, is_current=False
        )
        try:
            config, raw, _ = read_runtime_config(identity)
            inconsistencies = [
                message
                for message in check_metadata_consistency(identity, raw)
                if not message.startswith("Portable flag mismatch:")
            ]
            if inconsistencies:
                raise ConfigValidationError("; ".join(inconsistencies))
            health_errors = validate_origin_health(identity, config.get("origin"))
            health_errors.extend(validate_update_health(identity, config.get("update")))
            if health_errors:
                raise ConfigValidationError("; ".join(health_errors))
        except Exception as exc:
            if isinstance(exc, ConfigValidationError):
                raise ConfigValidationError(
                    f"Invalid registry seed for '{selector}': {exc}"
                ) from exc
            raise ConfigValidationError(f"Invalid registry seed {version_path}: {exc}") from exc
        packages.append(RegistryPackage(selector, selector_path, version_path))
    return packages


def search_registry(cache_root: Path, system: System, query: str = "") -> list[RegistryPackage]:
    """Return validated active-tree packages whose selector contains *query*.

    The search is case-insensitive, never uses the network, and returns every
    package for an empty query.
    """
    state = registry_status(cache_root, system)
    if state.tree_path is None:
        raise FileNotFoundError("No validated registry cache is available")
    needle = query.casefold()
    return [item for item in validate_registry_tree(state.tree_path) if needle in item.selector.casefold()]


def resolve_selector(cache_root: Path, system: System, selector: str) -> RegistryPackage:
    """Resolve one case-insensitive selector from the active validated tree."""
    matches = [item for item in search_registry(cache_root, system) if item.selector.casefold() == selector.casefold()]
    if not matches:
        raise ValueError(f"Registry package was not found: {selector}")
    if len(matches) > 1:
        raise ValueError(f"Registry selector is ambiguous: {selector}")
    return matches[0]


def sync_registry(
    cache_root: Path,
    system: System,
    *,
    source: str = OFFICIAL_SOURCE,
    offline: bool = False,
) -> ActionResult:
    """Fetch the registry and publish its validated tree.

    Parameters
    ----------
    cache_root : Path
        Registry cache directory from the manager configuration.
    system : System
        Boundary for downloads, Git and the admin-only checks.
    source : str, default=OFFICIAL_SOURCE
        An ``https://`` Git repository URL (cloned with a trusted Git, otherwise
        downloaded as its GitHub ZIP archive), or the ``http(s)://`` or ``file:``
        URL of a ZIP archive whose single top-level folder holds the packages.
    offline : bool, default=False
        Validate and report the existing cache without any download.

    Returns
    -------
    ActionResult
        ``synced``, ``current`` (the fetched revision is the one already
        cached), or ``offline``. On failure the previous validated tree stays
        active.
    """
    cache_root = Path(cache_root)
    current = registry_status(cache_root, system)
    if offline:
        if current.tree_path is None:
            return ActionResult(
                False,
                errors=["No validated registry cache is available in offline mode"],
                exit_code=EXIT_MUTATION_ERROR,
            )
        return ActionResult(True, status="offline", exit_code=EXIT_SUCCESS)

    registry_root = cache_root / REGISTRY_NAME
    work_parent = registry_root / ".work"
    work_parent.mkdir(parents=True, exist_ok=True)
    try:
        with tempfile.TemporaryDirectory(prefix="sync-", dir=str(work_parent)) as work_name:
            work = Path(work_name)

            # A trusted Git can name the remote revision without transferring it.
            git = trusted_git(system) if is_git_source(source) else None
            if git is not None and current.tree_path is not None:
                remote = git_remote_revision(system, git, source)
                if remote is not None and remote == current.revision:
                    validate_registry_tree(current.tree_path)
                    _write_state(registry_root, current, source=source, last_failure=None)
                    return ActionResult(True, status="current", exit_code=EXIT_SUCCESS)

            registry, revision = _obtain_registry(source, git, work, system)

            # A revision that is already active needs no rebuild; just re-validate
            # it and refresh the bookkeeping.
            if current.revision == revision and current.tree_path is not None:
                validate_registry_tree(current.tree_path)
                _write_state(registry_root, current, source=source, last_failure=None)
                return ActionResult(True, status="current", exit_code=EXIT_SUCCESS)

            # Copy the packages (never Git metadata), validate fully, then publish.
            pkgs = work / "pkgs"
            def furniture(directory: str, names: list[str]) -> list[str]:
                """Leave out Git metadata and top-level repository furniture (names starting with "_")."""
                top_level = Path(directory) == registry
                return [name for name in names if name == ".git" or (top_level and name.startswith("_"))]

            shutil.copytree(registry, pkgs, ignore=furniture)
            if not validate_registry_tree(pkgs):
                raise ConfigValidationError("The registry contains no packages")
            target = registry_root / "trees" / revision
            if target.exists():
                shutil.rmtree(target)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(pkgs, target / "pkgs")
        new_state = RegistryState(
            cache_root,
            revision=revision,
            source=source,
            synchronized_at=datetime.now(timezone.utc).isoformat(),
        )
        _write_state(registry_root, new_state, source=source, last_failure=None)
        return ActionResult(True, changed=True, status="synced", exit_code=EXIT_SUCCESS)
    except Exception as exc:
        _write_state(registry_root, current, source=current.source or source, last_failure=str(exc))
        return ActionResult(
            False,
            warnings=["The previous validated registry tree remains active."],
            errors=[f"Registry synchronization failed: {exc}"],
            exit_code=EXIT_MUTATION_ERROR,
        )
    finally:
        shutil.rmtree(work_parent, ignore_errors=True)


# ---------------------------------------------------------------------------
# Obtaining a registry: Git when it is trusted, otherwise the ZIP archive
# ---------------------------------------------------------------------------


def is_git_source(source: str) -> bool:
    """Return whether *source* names a Git repository rather than a ZIP archive."""
    parsed = urllib.parse.urlparse(source)
    if parsed.scheme.lower() != "https":
        return False
    path = parsed.path.rstrip("/")
    if path.lower().endswith(".git"):
        return True
    return parsed.netloc.lower() == "github.com" and len([part for part in path.split("/") if part]) == 2


def trusted_git(system: System) -> str | None:
    """Return a ``git.exe`` that only administrators can modify, or ``None``.

    Every ``git.exe`` on ``PATH`` is considered in order, and the first whose
    folder passes the admin-only check wins, so a user-writable copy earlier on
    ``PATH`` is skipped instead of run.
    """
    for entry in os.environ.get("PATH", "").split(os.pathsep):
        candidate = Path(entry.strip('"')) / "git.exe" if entry.strip() else None
        if candidate is None or not candidate.is_file():
            continue
        try:
            require_admin_only(system, candidate.resolve().parent)
        except UntrustedLocationError:
            continue
        return str(candidate)
    return None


def git_environment() -> dict[str, str]:
    """Return a child environment that ignores user Git settings and never prompts."""
    environment = {key: value for key, value in os.environ.items() if not key.upper().startswith("GIT_")}
    environment.update(GIT_TERMINAL_PROMPT="0", GIT_CONFIG_GLOBAL=os.devnull)
    return environment


def git_remote_revision(system: System, git: str, source: str) -> str | None:
    """Return the remote ``HEAD`` commit of *source* without cloning, or ``None`` on failure."""
    result = system.run(
        [git, "-c", "protocol.allow=never", "-c", "protocol.https.allow=always", "ls-remote", source, "HEAD"],
        env=git_environment(), timeout=60, on_line=subprocess_lines([git]),
    )
    match = re.match(r"([0-9a-f]{40})\s", result.stdout) if result.returncode == 0 else None
    return match.group(1) if match else None


def _obtain_registry(source: str, git: str | None, work: Path, system: System) -> tuple[Path, str]:
    """Fetch the registry into *work* and return its root folder and 40-hex revision."""
    if git is not None and is_git_source(source):
        log_info(f"Cloning registry: {source}")
        destination = work / "clone"
        command = [
            git, "-c", "protocol.allow=never", "-c", "protocol.https.allow=always",
            "-c", "core.symlinks=false", "-c", f"core.hooksPath={os.devnull}",
            "clone", "--depth", "1", "--single-branch", "--no-tags", "--quiet", source, str(destination),
        ]
        result = system.run(command, env=git_environment(), timeout=600, on_line=subprocess_lines(command))
        if result.returncode != 0:
            raise ConfigValidationError(f"git clone failed: {result.stderr.strip()}")
        head = system.run(
            [git, "-C", str(destination), "rev-parse", "HEAD"],
            env=git_environment(), on_line=subprocess_lines([git]),
        )
        revision = head.stdout.strip().lower()
        if not re.fullmatch(r"[0-9a-f]{40}", revision):
            raise ConfigValidationError("git clone did not report a commit")
        return destination, revision

    archive_path = work / "registry.zip"
    _download(archive_url(source), archive_path, system)
    revision = archive_revision(archive_path)
    return extract_archive(archive_path, work / "archive"), revision


def archive_url(source: str) -> str:
    """Return the ZIP archive URL for *source*.

    A GitHub repository URL designates the archive of its default branch; every
    other source must already be the URL of a ZIP archive.
    """
    if is_git_source(source):
        parsed = urllib.parse.urlparse(source)
        if parsed.netloc.lower() != "github.com":
            raise ConfigValidationError(
                f"No trusted Git is available, and an archive URL is only known for github.com repositories: {source}"
            )
        repository = parsed.path.rstrip("/")
        repository = repository[: -len(".git")] if repository.lower().endswith(".git") else repository
        return f"https://github.com{repository}/archive/HEAD.zip"
    return source


def _download(source: str, destination: Path, system: System) -> None:
    """Download *source* (HTTP, HTTPS, or ``file:``) to *destination* with progress."""
    if urllib.parse.urlparse(source).scheme.lower() not in {"http", "https", "file"}:
        raise ConfigValidationError(
            f"Registry source must be an http(s):// or file: URL to a ZIP archive: {source}"
        )
    log_info(f"Downloading registry: {source}")
    download_file(system, source, destination, label="Downloading registry")


def archive_revision(archive_path: Path) -> str:
    """Return a stable 40-hex revision for a registry archive.

    GitHub archives record their commit ID in the ZIP comment; any other
    archive is identified by the first 40 hex digits of its SHA-256 digest.
    """
    with zipfile.ZipFile(archive_path) as archive:
        comment = archive.comment.decode("ascii", errors="ignore").strip().lower()
    if re.fullmatch(r"[0-9a-f]{40}", comment):
        return comment
    return file_sha256(archive_path)[:40]


def extract_archive(archive_path: Path, destination: Path) -> Path:
    """Extract a registry archive safely and return the folder that holds the packages.

    Entries that are absolute, climb out with ``..``, are symlinks, or are named
    with a drive are rejected. GitHub wraps a repository in one top-level
    folder; when the archive has exactly one, that folder is the registry root.
    """
    destination.mkdir(parents=True)
    root = destination.resolve()
    with zipfile.ZipFile(archive_path) as archive:
        for info in archive.infolist():
            parts = PurePosixPath(info.filename)
            if parts.is_absolute() or ".." in parts.parts or ":" in info.filename:
                raise ConfigValidationError(f"Registry archive contains an unsafe path: {info.filename}")
            if (info.external_attr >> 16) & 0o170000 == 0o120000:
                raise ConfigValidationError(f"Registry archive contains a symlink: {info.filename}")
            target = (root / PurePosixPath(*parts.parts)).resolve() if parts.parts else root
            if not target.is_relative_to(root):
                raise ConfigValidationError(f"Registry archive contains an unsafe path: {info.filename}")
            if info.is_dir():
                target.mkdir(parents=True, exist_ok=True)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                with archive.open(info) as source, open(target, "wb") as sink:
                    shutil.copyfileobj(source, sink)
    children = list(root.iterdir())
    if len(children) == 1 and children[0].is_dir():
        return children[0]
    return root


def _validate_tree_entries(root: Path, path: Path) -> None:
    """Reject links, unsafe names, and manager-owned state recursively."""
    for entry in path.iterdir():
        _reject_reparse(entry, "registry tree")
        relative = entry.relative_to(root)
        if any(part in {".", ".."} or ":" in part for part in relative.parts):
            raise ConfigValidationError(f"Unsafe registry path: {relative}")
        if entry.name.casefold() in {"current", ".gupkg"}:
            raise ConfigValidationError(f"Registry tree contains reserved state: {relative}")
        if entry.is_dir():
            _validate_tree_entries(root, entry)


def _reject_reparse(path: Path, context: str) -> None:
    """Reject symbolic links and Windows reparse points before traversal."""
    if path.is_symlink():
        raise ConfigValidationError(f"{context} is a link: {path}")
    try:
        attributes = path.stat().st_file_attributes
    except (AttributeError, OSError):
        attributes = 0
    if attributes & 0x400:
        raise ConfigValidationError(f"{context} is a reparse point: {path}")


def _write_state(
    registry_root: Path,
    state: RegistryState,
    *,
    source: str,
    last_failure: str | None,
) -> None:
    """Atomically publish cache metadata while retaining the active tree."""
    write_toml(registry_root / "state.toml", {
        "revision": state.revision or "",
        "source": source,
        "synchronized_at": state.synchronized_at or "",
        "last_failure": last_failure or "",
    })
